function glyph(Icon: typeof InboxIcon, name: string): TablerIcon {
  const Component=forwardRef<SVGSVGElement,IconProps>(function SidebarGlyph({size=24,stroke,strokeWidth,color,fill,...props},ref){
    return <Icon ref={ref} width={size} height={size} color={color} fill={fill ?? 'none'}
      stroke={typeof stroke==='string' ? stroke : 'currentColor'} strokeWidth={strokeWidth ?? (typeof stroke==='number' ? stroke : 1.6)}
      aria-hidden={props['aria-label'] || props.title ? undefined : true}
      data-memail-icon-set="heroicons" data-memail-icon={name} {...props}/>;
  });
  Component.displayName=`Sidebar${name}`;
  return Component;
}
