function glyph(Icon: typeof InboxIcon, name: string, filled = false): TablerIcon {
  const Component = forwardRef<SVGSVGElement, IconProps>(function MemailHeroicon(
    {size = 24, stroke, strokeWidth, color, fill, ...props}, ref,
  ) {
    return <Icon ref={ref} width={size} height={size} color={color}
      fill={fill ?? (filled ? 'currentColor' : 'none')}
      stroke={typeof stroke === 'string' ? stroke : filled ? 'none' : 'currentColor'}
      strokeWidth={strokeWidth ?? (typeof stroke === 'number' ? stroke : 1.6)}
      aria-hidden={props['aria-label'] || props['aria-labelledby'] || props.title ? undefined : true}
      data-memail-glyph="" data-memail-icon-set="heroicons" data-memail-icon={name} {...props}/>;
  });
  Component.displayName = `Memail${name}`;
  // Glyph props are usually stable across mailbox updates. Avoid rendering
  // both the compatibility wrapper and vendor SVG again for unchanged props.
  return memo(Component);
}
