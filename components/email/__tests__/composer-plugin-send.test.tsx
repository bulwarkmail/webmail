// #1207: after a plugin (S/MIME) sent the message itself the composer stayed
// open and empty, and a plugin that failed or was cancelled still had the
// draft deleted. A throwing plugin let the message go out unsigned.

const DRAFT = {
  to: 'bob@example.com',
  cc: '',
  bcc: '',
  subject: 'Signed hello',
  body: '<p>Hi</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'compose' as const,
  draftId: null,
};

function renderComposer() {
  const onSend = vi.fn();
  const onClose = vi.fn();
  render(<EmailComposer initialData={DRAFT} onSend={onSend} onClose={onClose} />);
  fireEvent.click(screen.getAllByTestId('composer-send')[0]);
  return { onSend, onClose };
}

describe('composer send taken over by a plugin (#1207)', () => {
  afterEach(() => {
    vi.clearAllMocks();
  });

  it('closes after the plugin sent the message', async () => {
    hoisted.takeOver.mockResolvedValue('handled');
    const { onSend, onClose } = renderComposer();

    await waitFor(() => expect(onClose).toHaveBeenCalledTimes(1));
    expect(onSend).not.toHaveBeenCalled();
  });

  it('keeps the message when the plugin aborts', async () => {
    hoisted.takeOver.mockResolvedValue('aborted');
    const { onSend, onClose } = renderComposer();

    await waitFor(() => expect(hoisted.takeOver).toHaveBeenCalledTimes(1));
    await waitFor(() => expect(screen.getAllByTestId('composer-send')[0]).not.toBeDisabled());
    expect(screen.getByDisplayValue('Signed hello')).toBeInTheDocument();
    expect(onSend).not.toHaveBeenCalled();
    expect(onClose).not.toHaveBeenCalled();
    expect(hoisted.toastError).not.toHaveBeenCalled();
  });

  it('does not send unsigned when the plugin fails', async () => {
    hoisted.takeOver.mockResolvedValue('failed');
    const { onSend, onClose } = renderComposer();

    await waitFor(() => expect(hoisted.toastError).toHaveBeenCalledWith('send_plugin_failed'));
    expect(screen.getByDisplayValue('Signed hello')).toBeInTheDocument();
    expect(onSend).not.toHaveBeenCalled();
    expect(onClose).not.toHaveBeenCalled();
  });

  it('sends normally when no plugin takes the send', async () => {
    hoisted.takeOver.mockResolvedValue('default');
    const { onSend } = renderComposer();

    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
  });

  it('sends the headers a plugin added to the outgoing message', async () => {
    hoisted.takeOver.mockResolvedValue('default');
    hoisted.transform.mockImplementationOnce(async (email: unknown) => ({
      ...(email as Record<string, unknown>),
      headers: { 'X-Classification': 'Internal' },
    }));
    const { onSend } = renderComposer();

    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    expect(onSend.mock.calls[0][0].headers).toEqual({ 'X-Classification': 'Internal' });
  });
});
