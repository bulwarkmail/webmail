// compose-p3-1: the Undo time was fixed at the click, before a plugin's
// send check waited for the user. Answering after 10 s left a time in the
// past, and the server refused the send.

const DRAFT = {
  to: 'bob@example.com',
  cc: '',
  bcc: '',
  subject: 'Hello',
  body: '<p>Hi</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'compose' as const,
  draftId: null,
};

describe('the Undo send time after a question', () => {
  afterEach(() => {
    vi.restoreAllMocks();
    vi.clearAllMocks();
  });

  it('starts once a send check that waited 10 seconds is answered', async () => {
    let clock = Date.parse('2026-11-04T10:00:00Z');
    vi.spyOn(Date, 'now').mockImplementation(() => clock);
    let answer: (outcome: string) => void = () => {};
    hoisted.interceptOutcome.mockImplementationOnce(() => new Promise((resolve) => { answer = resolve; }));
    const onSend = vi.fn();
    render(<EmailComposer initialData={DRAFT} onSend={onSend} onClose={vi.fn()} />);

    fireEvent.click(screen.getAllByTestId('composer-send')[0]);
    await waitFor(() => expect(hoisted.interceptOutcome).toHaveBeenCalledTimes(1));
    // The user reads the plugin's question for 10 seconds, then says send.
    clock += 10_000;
    answer('allowed');

    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    const delayedUntil = onSend.mock.calls[0][0].delayedUntil as string;
    // Two times made in the same millisecond differ by one.
    expect(Date.parse(delayedUntil) - clock).toBeGreaterThanOrEqual(5_000);
    expect(Date.parse(delayedUntil) - clock).toBeLessThan(5_010);
    // A crypto plugin that takes over gets the full time too.
    const takeOverAt = Date.parse((hoisted.takeOver.mock.calls[0] as unknown as [{ delayedUntil: string }])[0].delayedUntil);
    expect(takeOverAt - clock).toBeGreaterThanOrEqual(5_000);
    expect(takeOverAt - clock).toBeLessThan(5_010);
  });
});
