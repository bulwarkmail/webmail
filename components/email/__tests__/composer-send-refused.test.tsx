// A host that sends nothing answers onSend with false: its login has no
// connection, or (new) the login the From address belongs to has none. The
// message was not sent, so the composer still holds it: recipients, subject
// and text stay, and the draft is still the composer's draft.

const READY = {
  to: 'bob@example.com',
  cc: '',
  bcc: '',
  subject: 'Quarterly numbers',
  body: '<p>Here they are.</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'compose' as const,
  draftId: 'draft-3',
};

const sendButton = () => screen.getAllByTestId('composer-send')[0] as HTMLButtonElement;
const subject = () => (screen.getByTestId('composer-subject') as HTMLInputElement).value;

describe('a send the host refused (onSend resolved false)', () => {
  it('leaves the message in the composer', async () => {
    const onSend = vi.fn().mockResolvedValue(false);
    const onSendFailed = vi.fn();
    render(<EmailComposer initialData={READY} onSend={onSend} onSendFailed={onSendFailed} />);
    expect(subject()).toBe('Quarterly numbers');

    fireEvent.click(sendButton());
    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    await new Promise((resolve) => setTimeout(resolve, 50));

    // Either the composer still shows the message, or it handed it back to the host.
    const handedBack = onSendFailed.mock.calls.length > 0;
    expect(handedBack || subject() === 'Quarterly numbers').toBe(true);
  });

  it('a second Send sends the same message again, not an empty one', async () => {
    const onSend = vi.fn().mockResolvedValueOnce(false).mockResolvedValue(undefined);
    render(<EmailComposer initialData={READY} onSend={onSend} />);

    fireEvent.click(sendButton());
    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    await new Promise((resolve) => setTimeout(resolve, 50));
    fireEvent.click(sendButton());
    await new Promise((resolve) => setTimeout(resolve, 200));

    expect(onSend).toHaveBeenCalledTimes(2);
    expect(onSend.mock.calls[1][0]).toMatchObject({ to: ['bob@example.com'], subject: 'Quarterly numbers' });
  });
});
