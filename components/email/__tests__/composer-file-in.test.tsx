// ─── Tests ────────────────────────────────────────────────────────────────────

const READY = {
  to: 'bob@example.com',
  cc: '',
  bcc: '',
  subject: 'Re: Quarterly numbers',
  body: '<p>Here they are.</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'reply' as const,
  draftId: 'draft-3',
};

const folder = (id: string, name: string, role?: string) => ({
  id, name, role, sortOrder: 0, totalEmails: 0, unreadEmails: 0, totalThreads: 0, unreadThreads: 0,
  myRights: { mayAddItems: true }, isSubscribed: true,
}) as never;
const FOLDERS = [folder('inbox', 'Inbox', 'inbox'), folder('projects', 'Projects')];

const sendButton = () => screen.getAllByTestId('composer-send')[0] as HTMLButtonElement;

describe('File in folder', () => {
  it('sends the picked folder with the message', async () => {
    const onSend = vi.fn().mockResolvedValue(undefined);
    render(<EmailComposer initialData={READY} mode="reply" fileTargets={FOLDERS} onSend={onSend} />);

    fireEvent.click(screen.getByTestId('composer-file-in'));
    fireEvent.click(await screen.findByTestId('composer-file-in:projects'));
    expect(screen.getByTestId('composer-file-in').getAttribute('aria-label')).toBe('file_in_chosen');

    fireEvent.click(sendButton());
    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    expect(onSend.mock.calls[0][0]).toMatchObject({ fileInMailboxId: 'projects' });
    expect(onSend.mock.calls[0][1]).toMatchObject({ fileInMailboxId: 'projects' });
  });

  it('files nothing until a folder is picked, or once it is taken back', async () => {
    const onSend = vi.fn().mockResolvedValue(undefined);
    render(<EmailComposer initialData={{ ...READY, fileInMailboxId: 'projects' }} mode="reply" fileTargets={FOLDERS} onSend={onSend} />);

    fireEvent.click(screen.getByTestId('composer-file-in'));
    fireEvent.click(await screen.findByTestId('composer-file-in-none'));

    fireEvent.click(sendButton());
    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    expect(onSend.mock.calls[0][0].fileInMailboxId).toBeUndefined();
  });

  it('drops a folder the host no longer offers', async () => {
    const onSend = vi.fn().mockResolvedValue(undefined);
    render(<EmailComposer initialData={{ ...READY, fileInMailboxId: 'gone' }} mode="reply" fileTargets={FOLDERS} onSend={onSend} />);
    fireEvent.click(sendButton());
    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    expect(onSend.mock.calls[0][0].fileInMailboxId).toBeUndefined();
  });

  it('is not offered without folders', () => {
    render(<EmailComposer initialData={READY} mode="reply" onSend={vi.fn()} />);
    expect(screen.queryByTestId('composer-file-in')).toBeNull();
  });
});
