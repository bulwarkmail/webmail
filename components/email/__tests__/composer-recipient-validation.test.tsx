// ─── Tests ────────────────────────────────────────────────────────────────────

const DRAFT = {
  to: '',
  cc: '',
  bcc: '',
  subject: 'Lunch',
  body: '<p>Hello there</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'compose' as const,
  draftId: null,
};

const toInput = () => screen.getByPlaceholderText('to_placeholder') as HTMLInputElement;
const sendButton = () => screen.getAllByTestId('composer-send')[0] as HTMLButtonElement;

describe('composer recipient validation', () => {
  beforeEach(() => {
    toastError.mockClear();
    updateSetting.mockClear();
    editorKeyDown.mockClear();
  });

  it('adds a typed address when a comma follows it', () => {
    render(<EmailComposer initialData={DRAFT} />);
    const input = toInput();
    fireEvent.change(input, { target: { value: 'bob@example.com' } });
    fireEvent.keyDown(input, { key: ',' });

    expect(screen.getByText('bob@example.com')).toBeInTheDocument();
    expect(input.value).toBe('');
  });

  it('leaves a comma inside a display name alone', () => {
    render(<EmailComposer initialData={DRAFT} />);
    const input = toInput();
    fireEvent.change(input, { target: { value: '"Doe' } });
    const event = fireEvent.keyDown(input, { key: ',' });

    // Not prevented, so the browser types the comma.
    expect(event).toBe(true);
    expect(input.value).toBe('"Doe');
  });

  it('splits a typed list into one chip per entry on blur and marks the bad one', () => {
    render(<EmailComposer initialData={DRAFT} />);
    const input = toInput();
    fireEvent.change(input, { target: { value: 'bob@example.com,notanemail' } });
    fireEvent.blur(input);

    expect(screen.getByText('bob@example.com').closest('[data-invalid]')).toBeNull();
    expect(screen.getByText('notanemail').closest('[data-invalid]')).not.toBeNull();
  });

  it('does not send while a recipient is not an address and names it', async () => {
    const onSend = vi.fn();
    render(<EmailComposer initialData={{ ...DRAFT, to: 'bob@example.com, user' }} onSend={onSend} />);

    fireEvent.click(sendButton());
    await act(async () => {});

    expect(onSend).not.toHaveBeenCalled();
    expect(toastError).toHaveBeenCalledWith('validation.invalid_recipients');
  });

  it('does not send a group whose member is not an address and names the member', async () => {
    const onSend = vi.fn();
    render(<EmailComposer initialData={{ ...DRAFT, to: 'Team: bob@example.com, junk;' }} onSend={onSend} />);

    expect(screen.getByText('Team (2)').closest('[data-invalid]')).not.toBeNull();

    fireEvent.click(sendButton());
    await act(async () => {});

    expect(onSend).not.toHaveBeenCalled();
    expect(toastError).toHaveBeenCalledWith('validation.invalid_recipients');
  });

  it('sends when every recipient is an address', async () => {
    const onSend = vi.fn();
    render(<EmailComposer initialData={{ ...DRAFT, to: 'bob@example.com' }} onSend={onSend} />);

    fireEvent.click(sendButton());

    await waitFor(() => expect(onSend).toHaveBeenCalledTimes(1));
    expect(toastError).not.toHaveBeenCalled();
  });
});
